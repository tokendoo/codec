//! Derive a symbol alphabet from a tokenizer vocabulary (TOK-007).
//!
//! Kept in `tokendoo-bench`: the Worker must not gain a vocabulary dependency.
//! The codec receives only the frozen symbol list that this module produces.

use std::collections::BTreeSet;

use serde_json::Value;
use tiktoken_rs::CoreBPE;

/// Maximum symbols published into a derived table.
pub const DERIVED_CAPACITY: usize = 2048;

/// Tabular sentinel reserved by bare-family alphabets.
pub const TABULAR_SENTINEL: &str = "__T";

/// Return every vocabulary string that encodes to exactly one ordinary token.
pub fn single_token_strings(bpe: &CoreBPE, vocab_size: u32) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for rank in 0..vocab_size {
        let Ok(s) = bpe.decode(&[rank]) else {
            continue;
        };
        if s.is_empty() {
            continue;
        }
        if bpe.encode_ordinary(&s).len() == 1 {
            out.insert(s);
        }
    }
    out
}

/// Admissibility filter for a candidate symbol spelling.
pub fn is_admissible(s: &str) -> bool {
    if s.is_empty() || s == TABULAR_SENTINEL {
        return false;
    }
    if s.chars().any(|c| c.is_control()) {
        return false;
    }
    // Natural-language words of length ≥ 3 collide with real JSON values and
    // force the whole intern transform off. Keep short / non-alpha spellings.
    if s.len() >= 3 && s.chars().all(|c| c.is_ascii_alphabetic()) {
        return false;
    }
    json_string_roundtrips(s)
}

fn json_string_roundtrips(s: &str) -> bool {
    let value = Value::String(s.to_string());
    let Ok(encoded) = serde_json::to_string(&value) else {
        return false;
    };
    let Ok(parsed) = serde_json::from_str::<Value>(&encoded) else {
        return false;
    };
    parsed.as_str() == Some(s)
}

/// Deterministically derive an ordered symbol list from single-token candidates.
///
/// Sort key: UTF-8 length ascending, then lexicographic codepoint order.
/// Truncate to [`DERIVED_CAPACITY`]. The same input set always yields the same
/// list.
pub fn derive_alphabet(candidates: &BTreeSet<String>) -> Vec<String> {
    let mut admitted: Vec<&String> = candidates.iter().filter(|s| is_admissible(s)).collect();
    admitted.sort_by(|a, b| a.len().cmp(&b.len()).then_with(|| a.cmp(b)));
    admitted
        .into_iter()
        .take(DERIVED_CAPACITY)
        .cloned()
        .collect()
}

/// Render a Rust source file embedding `symbols` as `pub static SYMBOLS`.
pub fn render_symbols_rs(module_doc: &str, symbols: &[String]) -> String {
    let mut out = String::new();
    out.push_str("//! ");
    out.push_str(module_doc);
    out.push_str("\n//!\n//! Generated by `tokendoo-derive-alphabet`. Do not edit by hand.\n\n");
    out.push_str("/// Frozen symbol spellings, shortest-first.\n");
    out.push_str("pub static SYMBOLS: &[&str] = &[\n");
    for s in symbols {
        out.push_str("    ");
        out.push_str(&format_rust_string(s));
        out.push_str(",\n");
    }
    out.push_str("];\n");
    out
}

fn format_rust_string(s: &str) -> String {
    // Prefer debug formatting — it produces a valid Rust string literal.
    format!("{s:?}")
}

/// Single-token strings from a HuggingFace `tokenizers` vocabulary.
pub fn single_token_strings_hf(tokenizer: &tokenizers::Tokenizer) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for (token, _id) in tokenizer.get_vocab(false) {
        if token.is_empty() {
            continue;
        }
        // Skip SentencePiece / special markers that are not usable as JSON symbols.
        if token.starts_with('<') || token.starts_with('▁') || token.starts_with("##") {
            continue;
        }
        if let Ok(encoding) = tokenizer.encode(token.as_str(), false) {
            if encoding.get_ids().len() == 1 {
                out.insert(token);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use tiktoken_rs::cl100k_base;

    #[test]
    fn derivation_is_deterministic() {
        let bpe = cl100k_base().expect("cl100k");
        // Small probe: ranks 0..4000 cover enough short tokens for a stable list.
        let a = derive_alphabet(&single_token_strings(&bpe, 4_000));
        let b = derive_alphabet(&single_token_strings(&bpe, 4_000));
        assert_eq!(a, b);
        assert!(!a.is_empty());
        assert!(a.len() <= DERIVED_CAPACITY);
        for s in &a {
            assert!(is_admissible(s), "{s:?} should be admissible");
            assert_eq!(bpe.encode_ordinary(s).len(), 1);
        }
        // Sorted by length then lex.
        for w in a.windows(2) {
            assert!(w[0].len() <= w[1].len());
            if w[0].len() == w[1].len() {
                assert!(w[0] <= w[1]);
            }
        }
    }

    #[test]
    fn natural_words_are_rejected() {
        assert!(!is_admissible("the"));
        assert!(!is_admissible("status"));
        assert!(is_admissible("a"));
        assert!(is_admissible("0"));
        assert!(!is_admissible("__T"));
        assert!(!is_admissible(""));
    }
}
